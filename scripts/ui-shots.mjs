// Local visual check: drive the guided demo and save screenshots. Usage: node scripts/ui-shots.mjs <baseUrl> <outDir>
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const [base = 'http://localhost:3111', out = 'data/shots'] = process.argv.slice(2);
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const errors = [];
async function flow(name, viewport) {
  const page = await browser.newPage({ viewport });
  page.on('pageerror', (e) => errors.push(`${name}: ${e.message}`));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(`${name} console: ${m.text()}`); });
  await page.goto(base);
  await page.getByText('Talking to Maya').waitFor();
  const shot = async (n) => { await page.waitForTimeout(450); await page.screenshot({ path: `${out}/${name}-${n}.png`, fullPage: n.endsWith('full') }); };
  await shot('01-start');
  await page.getByRole('button', { name: 'Ask about deliveries' }).click();
  await page.waitForTimeout(400);
  await shot('02-ask');
  await page.getByRole('button', { name: 'Book the sofa', exact: true }).click();
  await page.locator('.ask-card').first().waitFor();
  if (viewport.width < 900) await page.getByRole('tab', { name: 'Evidence' }).click();
  await shot('03-conflict');
  await shot('03-conflict-full');
  if (viewport.width < 900) await page.getByRole('tab', { name: 'Assistant' }).click();
  await page.locator('.ask-card').first().getByRole('button', { name: 'Afternoons' }).click();
  await page.locator('.booking').first().waitFor();
  await shot('04-booked');
  await page.getByRole('button', { name: 'Jump 30 days ahead' }).click();
  await page.waitForTimeout(300);
  await page.getByRole('button', { name: 'Send the repair to the office' }).click();
  await page.locator('.ask-card').nth(1).waitFor();
  await shot('05-stale');
  if (viewport.width < 900) await page.getByRole('tab', { name: 'Evidence' }).click();
  await shot('05-stale-evidence');
  if (viewport.width < 900) await page.getByRole('tab', { name: 'Assistant' }).click();
  await page.locator('.ask-card').nth(1).getByRole('button', { name: /Yes, still/ }).click();
  await page.locator('.booking').nth(1).waitFor();
  await shot('06-rebooked');
  await page.getByRole('button', { name: 'Forget the private location' }).click();
  await page.getByRole('dialog').waitFor();
  await shot('07-forget-dialog');
  await page.getByRole('button', { name: 'Forget it' }).click();
  await page.getByText('Forgotten, and verified').waitFor();
  await shot('08-receipt');
  await page.getByRole('dialog').getByRole('button', { name: 'Run the proofs' }).click();
  await page.locator('.proof-pass').nth(4).waitFor({ timeout: 10000 }).catch(() => {});
  await shot('09-proofs');
  const proofs = await page.locator('.proofs li').allInnerTexts();
  console.log(name, 'proofs:\n  ' + proofs.join('\n  '));
  await page.getByRole('dialog').getByRole('button', { name: 'Close' }).click();
  if (viewport.width < 900) await page.getByRole('tab', { name: 'Memory' }).click();
  await page.getByRole('tab', { name: /Forgotten/ }).click();
  await shot('10-memory');
  await page.screenshot({ path: `${out}/${name}-11-full.png`, fullPage: true });
  await page.close();
}
await flow('desktop', { width: 1600, height: 1000 });
await flow('mobile', { width: 390, height: 844 });
await browser.close();
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors');
